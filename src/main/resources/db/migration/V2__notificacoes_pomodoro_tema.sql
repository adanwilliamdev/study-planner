-- Preferencia de tema (claro/escuro) por usuario
ALTER TABLE usuarios ADD COLUMN tema VARCHAR(10) DEFAULT 'light' NOT NULL;

-- Notificacoes persistidas: quem estava offline ainda as ve ao entrar
CREATE TABLE notificacoes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL,
    mensagem   VARCHAR(300) NOT NULL,
    criada_em  TIMESTAMP    NOT NULL,
    lida       BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT fk_notificacoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);
CREATE INDEX idx_notificacoes_usuario ON notificacoes (usuario_id, lida);

-- Historico de focos concluidos (alimenta as estatisticas do painel)
CREATE TABLE sessoes_pomodoro (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT    NOT NULL,
    materia_id   BIGINT,
    minutos      INTEGER   NOT NULL,
    concluida_em TIMESTAMP NOT NULL,
    CONSTRAINT fk_pomodoro_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_pomodoro_materia FOREIGN KEY (materia_id) REFERENCES materias (id) ON DELETE SET NULL
);
CREATE INDEX idx_pomodoro_usuario_data ON sessoes_pomodoro (usuario_id, concluida_em);
