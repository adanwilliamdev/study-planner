CREATE TABLE usuarios (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    senha VARCHAR(100) NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE usuario_roles (
    usuario_id BIGINT      NOT NULL,
    role       VARCHAR(50) NOT NULL,
    PRIMARY KEY (usuario_id, role),
    CONSTRAINT fk_roles_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);

CREATE TABLE materias (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    cor           VARCHAR(7),
    carga_horaria INTEGER,
    usuario_id    BIGINT       NOT NULL,
    CONSTRAINT fk_materias_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);
CREATE INDEX idx_materias_usuario ON materias (usuario_id);

CREATE TABLE tarefas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo             VARCHAR(150) NOT NULL,
    descricao          VARCHAR(1000),
    data_entrega       DATE,
    prioridade         VARCHAR(10),
    status             VARCHAR(20),
    materia_id         BIGINT,
    usuario_id         BIGINT       NOT NULL,
    ultima_notificacao DATE,
    CONSTRAINT fk_tarefas_materia FOREIGN KEY (materia_id) REFERENCES materias (id),
    CONSTRAINT fk_tarefas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);
CREATE INDEX idx_tarefas_usuario_prazo ON tarefas (usuario_id, data_entrega);
CREATE INDEX idx_tarefas_materia ON tarefas (materia_id);

CREATE TABLE cronogramas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id     BIGINT      NOT NULL,
    dia_da_semana  VARCHAR(10) NOT NULL,
    horario_inicio TIME        NOT NULL,
    horario_fim    TIME        NOT NULL,
    status         VARCHAR(15),
    CONSTRAINT fk_cronogramas_materia FOREIGN KEY (materia_id) REFERENCES materias (id)
);
CREATE INDEX idx_cronogramas_materia ON cronogramas (materia_id);

CREATE TABLE materiais_estudo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(150) NOT NULL,
    tipo           VARCHAR(10),
    url_ou_caminho VARCHAR(1000),
    materia_id     BIGINT       NOT NULL,
    CONSTRAINT fk_materiais_materia FOREIGN KEY (materia_id) REFERENCES materias (id)
);
CREATE INDEX idx_materiais_materia ON materiais_estudo (materia_id);
