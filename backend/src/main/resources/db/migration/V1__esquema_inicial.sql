-- Esquema inicial (PostgreSQL). Deve refletir as entidades JPA: o perfil "prod" usa ddl-auto=validate.

CREATE TABLE usuarios (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);
CREATE UNIQUE INDEX uk_usuarios_email_lower ON usuarios (LOWER(email));

CREATE TABLE usuario_roles (
    usuario_id BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    role       VARCHAR(255) NOT NULL,
    PRIMARY KEY (usuario_id, role)
);

CREATE TABLE materias (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(255) NOT NULL,
    cor           VARCHAR(255),
    carga_horaria INTEGER,
    usuario_id    BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE
);
CREATE INDEX idx_materias_usuario ON materias (usuario_id);

CREATE TABLE tarefas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo             VARCHAR(255) NOT NULL,
    descricao          VARCHAR(1000),
    data_entrega       DATE,
    prioridade         VARCHAR(255),
    status             VARCHAR(255),
    materia_id         BIGINT REFERENCES materias (id),
    usuario_id         BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    ultima_notificacao DATE,
    concluida_em       DATE
);
CREATE INDEX idx_tarefas_usuario ON tarefas (usuario_id);
CREATE INDEX idx_tarefas_vencimento ON tarefas (data_entrega) WHERE status <> 'CONCLUIDO';

CREATE TABLE cronogramas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id     BIGINT       NOT NULL REFERENCES materias (id),
    dia_da_semana  VARCHAR(255) NOT NULL,
    horario_inicio TIME         NOT NULL,
    horario_fim    TIME         NOT NULL,
    status         VARCHAR(255),
    concluida_em   DATE
);
CREATE INDEX idx_cronogramas_materia ON cronogramas (materia_id);

CREATE TABLE materiais_estudo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo          VARCHAR(255) NOT NULL,
    tipo            VARCHAR(255),
    url_ou_caminho  VARCHAR(1000),
    materia_id      BIGINT NOT NULL REFERENCES materias (id)
);
CREATE INDEX idx_materiais_materia ON materiais_estudo (materia_id);

CREATE TABLE sessoes_foco (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT    NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    materia_id    BIGINT    REFERENCES materias (id) ON DELETE SET NULL,
    minutos       INTEGER   NOT NULL,
    data          DATE      NOT NULL,
    registrada_em TIMESTAMP NOT NULL
);
CREATE INDEX idx_sessoes_foco_usuario_data ON sessoes_foco (usuario_id, data);
